@Composable
fun AutoTaskBreakdownScreen(
    onBack: () -> Unit
) {
    val context = LocalContext.current

    var assignments by remember {
        mutableStateOf(BuddyData.getAssignments(context).take(10))
    }
    var result by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf(false) }

    val totalHours = assignments.sumOf { it.estimatedHours }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .background(Color(0xFFFFEAF3))
            .verticalScroll(rememberScrollState())
            .padding(18.dp),
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        Text(
            text = "Auto Task Breakdown 🎀",
            fontSize = 27.sp,
            fontWeight = FontWeight.Bold,
            color = Color(0xFFB94E78)
        )

        Spacer(Modifier.height(8.dp))

        Text(
            text = "Your assignments will be planned together ♡",
            color = Color(0xFF806C99),
            fontSize = 14.sp
        )

        Spacer(Modifier.height(18.dp))

        if (assignments.isEmpty()) {
            Card(
                colors = CardDefaults.cardColors(
                    containerColor = Color.White
                ),
                shape = RoundedCornerShape(20.dp)
            ) {
                Text(
                    "You haven't added any assignments yet. Add an assignment first!",
                    modifier = Modifier.padding(18.dp),
                    color = Color(0xFF704A59)
                )
            }
        } else {
            Card(
                modifier = Modifier.fillMaxWidth(),
                colors = CardDefaults.cardColors(
                    containerColor = Color.White
                ),
                shape = RoundedCornerShape(20.dp)
            ) {
                Column(Modifier.padding(16.dp)) {
                    Text(
                        "Your assignments (${assignments.size}/10)",
                        fontWeight = FontWeight.Bold,
                        color = Color(0xFFB94E78),
                        fontSize = 18.sp
                    )

                    Spacer(Modifier.height(8.dp))

                    assignments.forEach { assignment ->
                        AssignmentBreakdownCard(assignment)
                        Spacer(Modifier.height(10.dp))
                    }

                    HorizontalDivider(color = Color(0xFFEDE4FA))

                    Spacer(Modifier.height(10.dp))

                    Text(
                        "Total estimated workload: ${"%.1f".format(totalHours)} hours",
                        fontWeight = FontWeight.SemiBold,
                        color = Color(0xFF806C99)
                    )
                }
            }

            Spacer(Modifier.height(16.dp))

            Button(
                onClick = {
                    val drafts = mutableListOf<DailyTodoDraft>()
                    val messages = mutableListOf<String>()

                    assignments.forEach { assignment ->
                        val deadline = parseAssignmentDeadline(assignment.deadline)

                        if (deadline == null) {
                            messages.add(
                                "${assignment.title}: deadline format could not be read."
                            )
                        } else {
                            val days = getPlanningDates(deadline)
                            if (days.isEmpty()) {
                                messages.add(
                                    "${assignment.title}: deadline has already passed."
                                )
                            } else {
                                val hours = assignment.estimatedHours
                                    .coerceAtLeast(0.5)

                                val sessionCount = ceil(hours).toInt()
                                    .coerceAtLeast(1)

                                val dates = spreadSessions(
                                    days = days,
                                    count = sessionCount
                                )

                                for (index in 0 until sessionCount) {
                                    val sessionHours = if (index == sessionCount - 1) {
                                        val remainder = hours - index
                                        if (remainder > 0.0) remainder else 1.0
                                    } else {
                                        1.0
                                    }

                                    val dateText = SimpleDateFormat(
                                        "yyyy-MM-dd",
                                        Locale.getDefault()
                                    ).format(dates[index])

                                    val taskTitle =
                                        "${assignment.title} — Study session ${index + 1}/$sessionCount (${String.format(Locale.getDefault(), "%.1f", sessionHours)} hr)"

                                    drafts.add(
                                        DailyTodoDraft(
                                            title = taskTitle,
                                            date = dateText,
                                            time = ""
                                        )
                                    )
                                }
                            }
                        }
                    }

                    var addedCount = 0
                    assignments.forEach { assignment ->
                        val assignmentDrafts = drafts.filter {
                            it.title.startsWith("${assignment.title} — Study session")
                        }
                        if (assignmentDrafts.isNotEmpty()) {
                            addedCount += DailyTodoData.addAssignmentTasks(
                                context,
                                assignment.id,
                                assignmentDrafts
                            )
                        }
                    }

                    result = if (addedCount > 0) {
                        "♡ $addedCount study tasks added to your Daily To-do!"
                    } else {
                        "No tasks were added. Check your assignment deadlines."
                    }

                    if (messages.isNotEmpty()) {
                        result += "\n\n" + messages.joinToString("\n")
                    }

                    generated = true
                },
                modifier = Modifier
                    .fillMaxWidth()
                    .height(58.dp),
                shape = RoundedCornerShape(30.dp),
                colors = ButtonDefaults.buttonColors(
                    containerColor = Color(0xFFD96FA5)
                )
            ) {
                Text(
                    "Create My Combined Study Plan ♡",
                    fontSize = 16.sp
                )
            }

            if (generated) {
                Spacer(Modifier.height(14.dp))

                Card(
                    modifier = Modifier.fillMaxWidth(),
                    colors = CardDefaults.cardColors(
                        containerColor = Color(0xFFEDE4FA)
                    ),
                    shape = RoundedCornerShape(18.dp)
                ) {
                    Text(
                        result,
                        modifier = Modifier.padding(16.dp),
                        color = Color(0xFF493746),
                        fontSize = 15.sp
                    )
                }
            }
        }

        Spacer(Modifier.height(18.dp))

        OutlinedButton(
            onClick = onBack,
            modifier = Modifier.fillMaxWidth()
        ) {
            Text("← Back to Dashboard")
        }
    }
}

@Composable
private fun AssignmentBreakdownCard(
    assignment: BuddyAssignment
) {
    val bitmap = remember(assignment.imageUri) {
        try {
            if (assignment.imageUri.isNotBlank()) {
                BitmapFactory.decodeFile(File(assignment.imageUri).absolutePath)
            } else null
        } catch (_: Exception) {
            null
        }
    }

    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(16.dp),
        colors = CardDefaults.cardColors(
            containerColor = Color(0xFFFFF4F9)
        )
    ) {
        Row(
            modifier = Modifier.padding(10.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            if (bitmap != null) {
                Image(
                    bitmap = bitmap.asImageBitmap(),
                    contentDescription = assignment.title,
                    contentScale = ContentScale.Crop,
                    modifier = Modifier
                        .size(76.dp)
                        .background(Color(0xFFEDE4FA), RoundedCornerShape(12.dp))
                )
            } else {
                Box(
                    modifier = Modifier
                        .size(76.dp)
                        .background(
                            Color(0xFFEDE4FA),
                            RoundedCornerShape(12.dp)
                        ),
                    contentAlignment = Alignment.Center
                ) {
                    Text("📚", fontSize = 28.sp)
                }
            }

            Spacer(Modifier.width(12.dp))

            Column(Modifier.weight(1f)) {
                Text(
                    assignment.title,
                    fontWeight = FontWeight.Bold,
                    color = Color(0xFF704A59)
                )
                Text(
                    "Subject: ${assignment.subject}",
                    fontSize = 12.sp,
                    color = Color(0xFF806C99)
                )
                Text(
                    "Deadline: ${assignment.deadline}",
                    fontSize = 12.sp,
                    color = Color(0xFF806C99)
                )
                Text(
                    "Estimated: ${assignment.estimatedHours} hours",
                    fontSize = 12.sp,
                    color = Color(0xFF806C99)
                )
            }
        }
    }
}

private fun parseAssignmentDeadline(value: String): Date? {
    val formats = listOf(
        "dd/MM/yyyy HH:mm",
        "dd/MM/yyyy hh:mm a",
        "yyyy-MM-dd HH:mm",
        "yyyy-MM-dd"
    )

    for (format in formats) {
        try {
            return SimpleDateFormat(
                format,
                Locale.getDefault()
            ).apply {
                isLenient = false
            }.parse(value)
        } catch (_: Exception) {
        }
    }
    return null
}

private fun getPlanningDates(deadline: Date): List<Date> {
    val today = Calendar.getInstance()
    today.set(Calendar.HOUR_OF_DAY, 0)
    today.set(Calendar.MINUTE, 0)
    today.set(Calendar.SECOND, 0)
    today.set(Calendar.MILLISECOND, 0)

    val lastDay = Calendar.getInstance().apply {
        time = deadline
        set(Calendar.HOUR_OF_DAY, 0)
        set(Calendar.MINUTE, 0)
        set(Calendar.SECOND, 0)
        set(Calendar.MILLISECOND, 0)
    }

    if (lastDay.before(today)) return emptyList()

    val dates = mutableListOf<Date>()
    val current = today.clone() as Calendar

    while (!current.after(lastDay)) {
        dates.add(current.time)
        current.add(Calendar.DAY_OF_YEAR, 1)
    }

    return dates
}

private fun spreadSessions(
    days: List<Date>,
    count: Int
): List<Date> {
    if (days.isEmpty()) return emptyList()

    return List(count) { index ->
        val dayIndex = if (count <= 1) {
            0
        } else {
            (index * (days.size - 1) / (count - 1))
        }
        days[dayIndex]
    }
}